import React, { useState } from 'react';
import { Pressable, StyleSheet, Text, View } from 'react-native';
import { NativeStackScreenProps } from '@react-navigation/native-stack';
import { VaultStackParamList } from '../../navigation/types';
import { Screen } from '../../components/Screen';
import { Button } from '../../components/Button';
import { Input } from '../../components/Input';
import { Glyph } from '../../components/Glyph';
import { Icon } from '../../components/Icon';
import { useVault } from '../../context/VaultContext';
import { DOCUMENT_TYPES, CATEGORY_ORDER } from '../../data/documentTypes';
import { maskReference, todayLabel } from '../../utils/format';
import { DocTypeId } from '../../types';
import { palette, radius, spacing, typography } from '../../theme';

type Props = NativeStackScreenProps<VaultStackParamList, 'AddDocument'>;

export function AddDocumentScreen({ navigation }: Props) {
  const { addDocument } = useVault();
  const [type, setType] = useState<DocTypeId | null>(null);
  const [title, setTitle] = useState('');
  const [reference, setReference] = useState('');
  const [scanned, setScanned] = useState(false);

  const canSave = type !== null && title.trim().length > 0;

  const handleSave = () => {
    if (!type || !canSave) {
      return;
    }
    const meta = DOCUMENT_TYPES[type];
    addDocument({
      id: `d-${Date.now()}`,
      type,
      title: title.trim(),
      reference: reference.trim() ? maskReference(reference.trim()) : 'Not specified',
      category:
        type === 'x' || type === 'xii'
          ? 'education'
          : type === 'bank' || type === 'insurance'
            ? 'financial'
            : type === 'other'
              ? 'personal'
              : 'government',
      addedAt: todayLabel(),
      size: scanned ? '1.0 MB' : '\u2014',
      fields: [
        { label: 'Reference', value: maskReference(reference.trim()) || '\u2014', masked: true },
        { label: 'Stored format', value: 'Encrypted file (AES-256-GCM)' },
      ],
    });
    navigation.goBack();
  };

  return (
    <Screen scroll style={styles.screen}>
      <View style={styles.header}>
        <Pressable onPress={() => navigation.goBack()} hitSlop={8} style={styles.closeButton}>
          <Icon name="close" size={18} color={palette.inkSoft} />
        </Pressable>
        <Text style={styles.headerTitle}>Add to vault</Text>
        <View style={styles.headerSpacer} />
      </View>

      <Text style={styles.label}>Select document type</Text>
      <View style={styles.typeGrid}>
        {CATEGORY_ORDER.map((id) => {
          const meta = DOCUMENT_TYPES[id];
          const active = type === id;
          return (
            <Pressable
              key={id}
              onPress={() => {
                setType(id);
                setTitle(meta.label);
              }}
              style={[styles.typeCard, active ? styles.typeCardActive : null]}
            >
              <Glyph mono={meta.mono} tint={meta.tint} soft={meta.soft} size={42} />
              <Text style={[styles.typeLabel, active ? styles.typeLabelActive : null]} numberOfLines={1}>
                {meta.label}
              </Text>
              {active ? (
                <View style={styles.typeCheck}>
                  <Icon name="check" size={12} color="#FFFFFF" />
                </View>
              ) : null}
            </Pressable>
          );
        })}
      </View>

      <Input
        label="Document name"
        value={title}
        onChangeText={setTitle}
        placeholder="e.g. Aadhaar Card"
        style={styles.field}
      />
      <Input
        label="Reference number (optional)"
        value={reference}
        onChangeText={setReference}
        placeholder="e.g. XXXX XXXX 3456"
        autoCapitalize="characters"
        style={styles.field}
      />

      <Button
        label={scanned ? 'Document attached' : 'Scan or upload file'}
        variant={scanned ? 'secondary' : 'secondary'}
        onPress={() => setScanned(true)}
        leading={<Icon name={scanned ? 'check' : 'scan'} size={18} color={palette.brand} />}
        style={styles.scanButton}
      />
      {scanned ? (
        <View style={styles.scannedNote}>
          <Icon name="check" size={14} color={palette.success} />
          <Text style={styles.scannedText}>Encrypted preview ready — file will be sealed before saving.</Text>
        </View>
      ) : null}

      <View style={styles.securityCard}>
        <Icon name="shieldCheck" size={20} color={palette.brand} />
        <Text style={styles.securityText}>
          Saved files are encrypted with AES-256-GCM. The key is generated by your device\u2019s
          secure hardware and never leaves it.
        </Text>
      </View>

      <Button label="Save to vault" onPress={handleSave} disabled={!canSave} style={styles.saveButton} />
    </Screen>
  );
}

const styles = StyleSheet.create({
  screen: {
    paddingTop: spacing.lg,
  },
  header: {
    flexDirection: 'row',
    alignItems: 'center',
    justifyContent: 'space-between',
    marginBottom: spacing.xl,
  },
  closeButton: {
    width: 40,
    height: 40,
    borderRadius: radius.md,
    backgroundColor: palette.surface,
    borderWidth: 1,
    borderColor: palette.border,
    alignItems: 'center',
    justifyContent: 'center',
  },
  headerTitle: {
    ...typography.heading,
  },
  headerSpacer: {
    width: 40,
  },
  label: {
    ...typography.label,
    marginBottom: spacing.md,
  },
  typeGrid: {
    flexDirection: 'row',
    flexWrap: 'wrap',
    gap: spacing.md,
    marginBottom: spacing.xxl,
  },
  typeCard: {
    width: '30.5%',
    alignItems: 'center',
    gap: spacing.sm,
    paddingVertical: spacing.md,
    borderRadius: radius.md,
    borderWidth: 1,
    borderColor: palette.border,
    backgroundColor: palette.surface,
  },
  typeCardActive: {
    borderColor: palette.brand,
    backgroundColor: palette.brandSoft,
  },
  typeLabel: {
    ...typography.caption,
    fontSize: 11,
    textAlign: 'center',
    paddingHorizontal: spacing.xs,
  },
  typeLabelActive: {
    color: palette.brand,
    fontWeight: '700',
  },
  typeCheck: {
    position: 'absolute',
    top: 8,
    right: 8,
    width: 18,
    height: 18,
    borderRadius: 9,
    backgroundColor: palette.brand,
    alignItems: 'center',
    justifyContent: 'center',
  },
  field: {
    marginBottom: spacing.lg,
  },
  scanButton: {
    marginBottom: spacing.md,
  },
  scannedNote: {
    flexDirection: 'row',
    alignItems: 'center',
    gap: 6,
    marginBottom: spacing.xl,
    paddingHorizontal: spacing.xs,
  },
  scannedText: {
    ...typography.caption,
    fontSize: 12,
    color: palette.success,
    flex: 1,
  },
  securityCard: {
    flexDirection: 'row',
    alignItems: 'flex-start',
    gap: spacing.md,
    backgroundColor: palette.brandSoft,
    borderRadius: radius.md,
    borderWidth: 1,
    borderColor: '#DDE2FF',
    padding: spacing.lg,
    marginBottom: spacing.xxl,
  },
  securityText: {
    ...typography.caption,
    fontSize: 12,
    lineHeight: 18,
    color: palette.inkSoft,
    flex: 1,
  },
  saveButton: {
    marginBottom: spacing.lg,
  },
});
